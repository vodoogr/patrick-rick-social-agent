import { writeFile } from "node:fs/promises";
import { getMigrations } from "better-auth/db/migration";
import { auth } from "../lib/auth";

async function main() {
  let database = auth.options.database;
  if (process.argv.includes("--empty-auth-schema")) {
    // Offline generation only: use after confirming no auth tables exist via Neon.
    const { Pool } = await import("pg");
    const pool = new Pool();
    const client = { query: async () => ({ rows: [], rowCount: 0 }), release() {}, on() {} };
    pool.connect = (async () => client) as unknown as typeof pool.connect;
    database = pool;
  }
  const plan = await getMigrations({ ...auth.options, database });
  if (plan.unsafeChanges.length || plan.schemaProblems.length) throw new Error("Schema requires manual review");
  const sql = await plan.compileMigrations();
  if (/\b(drop\s+table|truncate\s+table|delete\s+from)\b/i.test(sql)) throw new Error("Destructive migration refused");
  await writeFile("database/better-auth.sql", "-- Generated by Better Auth 1.7.14 from empty auth-schema snapshot; validated on isolated Neon audit branch.\n" + sql);
  console.log(JSON.stringify({ create: plan.toBeCreated.map(t => t.table), alter: plan.toBeAdded.map(t => t.table), indexes: plan.toBeAddedIndexes.length, empty: !sql.trim() }));
}
main().then(() => process.exit(0)).catch(() => { console.error("Migration planning failed; inspect connection and schema privately."); process.exit(1); });
